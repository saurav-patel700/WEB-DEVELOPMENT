let day=1;
switch (day){
    case 1:
        console.log("m");
        break;
    case 2:
        console.log("t");
        break;
    case 3:
        console.log("w");
        break;
    case 4:
        console.log("th");
        break;
    case 5:
        console.log("f");
        break;
    case 6:
        console.log("s");
        break;
    case 7:
        console.log("s");
        break;
    default:
        console.log("a");  
}